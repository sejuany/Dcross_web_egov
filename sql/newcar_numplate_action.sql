-- 애플리케이션 배포 전에 해당 DB 스키마에서 1회 실행한다.
CREATE TABLE TS_NUMPLATE_ACTION (
    ACTION_ID NUMBER(19) PRIMARY KEY,
    SERVICE_ID VARCHAR2(100 CHAR) NOT NULL,
    EVENT_CD VARCHAR2(30 CHAR) NOT NULL,
    CAR_NO VARCHAR2(20 CHAR) NOT NULL,
    REQUEST_ID VARCHAR2(36 CHAR) NOT NULL,
    DETAIL_TX VARCHAR2(1000 CHAR),
    INS_DATE TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE SEQUENCE SEQ_NUMPLATE_ACTION START WITH 1 INCREMENT BY 1 CACHE 100 NOCYCLE;
CREATE INDEX IX_NUMPLATE_ACTION_SERVICE ON TS_NUMPLATE_ACTION (SERVICE_ID, INS_DATE);

COMMENT ON TABLE TS_NUMPLATE_ACTION IS '고객 번호판 행동 및 서버 확정 결과 이력';
COMMENT ON COLUMN TS_NUMPLATE_ACTION.EVENT_CD IS
    'NUMBER_CLICK/CONFIRM_OPEN/CONFIRM_CANCEL: 브라우저 보고, CONFIRM_REQUEST/SUCCESS/FAILURE: 서버 처리';
COMMENT ON COLUMN TS_NUMPLATE_ACTION.REQUEST_ID IS '최종 확인 요청과 결과의 연결 ID';

